#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";

const repoRoot = process.cwd();
const domainPackRoot = path.resolve(repoRoot, "domain-packs");
const outputFile = path.resolve(
  repoRoot,
  "apps/web/lib/local-domain-catalog.generated.ts",
);

const manifests = {
  spaces: "spaceFiles",
  taxonomyNodes: "taxonomyNodeFiles",
  entityTypes: "entityTypeFiles",
  views: "viewFiles",
};

function listPackDirectories() {
  if (!fs.existsSync(domainPackRoot)) {
    return [];
  }
  return fs
    .readdirSync(domainPackRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((name) => path.join(domainPackRoot, name));
}

function readJsonFile(filePath) {
  const raw = fs.readFileSync(filePath, "utf8");
  return JSON.parse(raw);
}

function uniqueById(items) {
  const seen = new Set();
  const output = [];
  for (const item of items) {
    if (!item || typeof item.id !== "string") continue;
    if (seen.has(item.id)) continue;
    seen.add(item.id);
    output.push(item);
  }
  return output;
}

function readPackDocumentPack(rootPath, manifest, key, manifestKey) {
  const collected = [];
  const documents = manifest?.[manifestKey];
  if (!Array.isArray(documents)) {
    return collected;
  }
  for (const relPath of documents) {
    if (typeof relPath !== "string") continue;
    const absolutePath = path.resolve(rootPath, relPath);
    if (!fs.existsSync(absolutePath)) continue;
    try {
      collected.push(readJsonFile(absolutePath));
    } catch (error) {
      throw new Error(
        `failed to parse ${key} document ${absolutePath}: ${String(error)}`,
      );
    }
  }
  return collected;
}

function normalizeViewMap(viewDocuments) {
  const index = {};
  for (const item of viewDocuments) {
    if (!item || typeof item.entityTypeId !== "string") continue;
    if (index[item.entityTypeId]) continue;
    index[item.entityTypeId] = item;
  }
  return index;
}

function emitCode({ spaces, taxonomyNodes, entityTypes, viewMap }) {
  return `// Auto-generated by scripts/generate-web-domain-fallback.mjs\n// Do not edit manually; re-run script when domain-pack content changes.\n\nimport type { EntityType, KnowledgeSpace, TaxonomyNode, ViewDefinition } from "@hardatlas/contracts";\n\nexport const dynamicSpaces: KnowledgeSpace[] = ${JSON.stringify(
    spaces,
    null,
    2,
  )};\n\nexport const dynamicTaxonomyNodes: TaxonomyNode[] = ${JSON.stringify(
    taxonomyNodes,
    null,
    2,
  )};\n\nexport const dynamicEntityTypes: EntityType[] = ${JSON.stringify(
    entityTypes,
    null,
    2,
  )};\n\nexport const dynamicViewDefinitions: Record<string, ViewDefinition> = ${JSON.stringify(
    viewMap,
    null,
    2,
  )};\n`;
}

function main() {
  const spaces = [];
  const taxonomyNodes = [];
  const entityTypes = [];
  const views = [];

  for (const packPath of listPackDirectories()) {
    const manifestPath = path.join(packPath, "manifest.json");
    if (!fs.existsSync(manifestPath)) continue;

    const manifest = readJsonFile(manifestPath);
    spaces.push(
      ...readPackDocumentPack(
        packPath,
        manifest,
        "spaces",
        manifests.spaces,
      ),
    );
    taxonomyNodes.push(
      ...readPackDocumentPack(
        packPath,
        manifest,
        "taxonomy",
        manifests.taxonomyNodes,
      ),
    );
    entityTypes.push(
      ...readPackDocumentPack(
        packPath,
        manifest,
        "entity types",
        manifests.entityTypes,
      ),
    );
    views.push(
      ...readPackDocumentPack(packPath, manifest, "view", manifests.views),
    );
  }

  const payload = {
    spaces: uniqueById(spaces),
    taxonomyNodes: uniqueById(taxonomyNodes),
    entityTypes: uniqueById(entityTypes),
    viewMap: normalizeViewMap(uniqueById(views)),
  };

  fs.writeFileSync(outputFile, `${emitCode(payload)}\n`, "utf8");
}

main();
